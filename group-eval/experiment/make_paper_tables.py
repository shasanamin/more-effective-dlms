#!/usr/bin/env python3
"""Convert GroupEval bootstrap CSVs into conservative LaTeX table rows."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def esc(text: str) -> str:
    return text.replace("_", r"\_").replace("%", r"\%")


def f(row: dict[str, str], key: str, digits: int = 2) -> str:
    return f"{float(row[key]):.{digits}f}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scores", required=True, type=Path)
    parser.add_argument("--comparisons", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--baseline", default=None)
    args = parser.parse_args()

    scores = read_csv(args.scores)
    comparisons = read_csv(args.comparisons)
    lines = [
        "% Auto-generated by experiment/make_paper_tables.py",
        r"\begin{tabular}{lcc}",
        r"\toprule",
        r"Operating point & GEQ $\uparrow$ & GED $\uparrow$ \\",
        r"\midrule",
    ]
    for row in scores:
        lines.append(
            f"{esc(row['method_code'])} & "
            f"{f(row,'geq')} [{f(row,'geq_ci_low')}, {f(row,'geq_ci_high')}] & "
            f"{f(row,'ged')} [{f(row,'ged_ci_low')}, {f(row,'ged_ci_high')}] \\\\" 
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    if args.baseline:
        lines += [
            "% Exploratory candidate-minus-baseline differences",
            r"\begin{tabular}{lcc}",
            r"\toprule",
            r"Candidate & $\Delta$GEQ & $\Delta$GED \\",
            r"\midrule",
        ]
        for row in comparisons:
            if row.get("reference") != args.baseline:
                continue
            lines.append(
                f"{esc(row['candidate'])} & {float(row['delta_geq']):.2f} & "
                f"{float(row['delta_ged']):.2f} \\\\"
            )
        lines += [r"\bottomrule", r"\end{tabular}"]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
